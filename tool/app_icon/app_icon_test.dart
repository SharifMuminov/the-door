// Generates the app icon for iOS and Android from code.
//
//   flutter test tool/app_icon/app_icon_test.dart
//
// Writes every size listed in the iOS AppIcon.appiconset, the Android
// launcher mipmaps (legacy + adaptive) and a 1024 px master for the stores.
// iOS icons are written without an alpha channel, as App Store requires.
import 'dart:convert';
import 'dart:io';
import 'dart:math' as math;
import 'dart:typed_data';
import 'dart:ui';

import 'package:flutter_test/flutter_test.dart';

const _iosSet = 'ios/Runner/Assets.xcassets/AppIcon.appiconset';
const _androidRes = 'android/app/src/main/res';

/// Android density buckets: legacy icon is 48 dp, adaptive layers 108 dp.
const _densities = {
  'mdpi': 1.0,
  'hdpi': 1.5,
  'xhdpi': 2.0,
  'xxhdpi': 3.0,
  'xxxhdpi': 4.0,
};

void main() {
  testWidgets('render app icons', (tester) async {
    await tester.runAsync(() async {
      // iOS: every file named in Contents.json.
      final contents =
          jsonDecode(File('$_iosSet/Contents.json').readAsStringSync())
              as Map<String, dynamic>;
      for (final image
          in (contents['images'] as List).cast<Map<String, dynamic>>()) {
        final points = double.parse((image['size'] as String).split('x').first);
        final scale = double.parse(
          (image['scale'] as String).replaceAll('x', ''),
        );
        final px = (points * scale).round();
        await _write('$_iosSet/${image['filename']}', px, _full, opaque: true);
      }

      // Android legacy icons (pre-8.0 launchers).
      for (final e in _densities.entries) {
        final dir = '$_androidRes/mipmap-${e.key}';
        await _write(
          '$dir/ic_launcher.png',
          (48 * e.value).round(),
          _full,
          opaque: true,
        );
        await _write(
          '$dir/ic_launcher_background.png',
          (108 * e.value).round(),
          _background,
          opaque: true,
        );
        await _write(
          '$dir/ic_launcher_foreground.png',
          (108 * e.value).round(),
          _foreground,
          opaque: false,
        );
      }
      Directory('$_androidRes/mipmap-anydpi-v26').createSync(recursive: true);
      File(
        '$_androidRes/mipmap-anydpi-v26/ic_launcher.xml',
      ).writeAsStringSync(_adaptiveXml);

      // Master for store listings.
      await _write(
        'tool/app_icon/app_icon_1024.png',
        1024,
        _full,
        opaque: true,
      );
    });
  });
}

const _adaptiveXml = '''<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tool/app_icon/app_icon_test.dart -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
    <monochrome android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
''';

// =================================================================== drawing

void _full(Canvas c, double s) {
  _paintBackground(c, s);
  _paintDoor(c, s, scale: 1);
}

void _background(Canvas c, double s) => _paintBackground(c, s);

/// Adaptive foreground: the door shrunk into the 66 dp safe zone.
void _foreground(Canvas c, double s) => _paintDoor(c, s, scale: .64);

void _paintBackground(Canvas c, double s) {
  final rect = Rect.fromLTWH(0, 0, s, s);
  c.drawRect(
    rect,
    Paint()
      ..shader = Gradient.radial(
        Offset(s * .5, s * .6),
        s * .75,
        const [Color(0xFF3A2416), Color(0xFF140C08), Color(0xFF050404)],
        const [0, .45, 1],
      ),
  );
  // Faint floorboards.
  final floorY = s * .8;
  c.drawRect(
    Rect.fromLTWH(0, floorY, s, s - floorY),
    Paint()
      ..shader = Gradient.linear(Offset(0, floorY), Offset(0, s), const [
        Color(0xFF140D09),
        Color(0xFF050404),
      ]),
  );
  final seam = Paint()
    ..color = const Color(0x55000000)
    ..strokeWidth = math.max(1, s / 300);
  final vanish = Offset(s / 2, floorY - s * .6);
  for (var i = -6; i <= 6; i++) {
    final bottom = Offset(s / 2 + i * s * .18, s);
    final t = (floorY - vanish.dy) / (bottom.dy - vanish.dy);
    c.drawLine(Offset.lerp(vanish, bottom, t)!, bottom, seam);
  }
}

/// A door left ajar, light pouring through the gap — and someone in it.
void _paintDoor(Canvas c, double s, {required double scale}) {
  c.save();
  c.translate(s / 2, s / 2);
  c.scale(scale);
  c.translate(-s / 2, -s / 2);

  final frame = Rect.fromLTRB(s * .29, s * .19, s * .71, s * .8);
  final t = s * .035;
  final opening = Rect.fromLTRB(
    frame.left + t,
    frame.top + t,
    frame.right - t,
    frame.bottom,
  );

  // Glow behind everything.
  final gapCenter = Offset(
    opening.right - opening.width * .2,
    opening.center.dy,
  );
  c.drawCircle(
    gapCenter,
    s * .45,
    Paint()
      ..shader = Gradient.radial(gapCenter, s * .45, const [
        Color(0x55E0A060),
        Color(0x00E0A060),
      ]),
  );

  // Frame.
  c.drawRect(
    frame,
    Paint()
      ..shader = Gradient.linear(
        frame.centerLeft,
        frame.centerRight,
        const [
          Color(0xFF1A110C),
          Color(0xFF45301F),
          Color(0xFF2E2017),
          Color(0xFF1A110C),
        ],
        const [0, .32, .7, 1],
      ),
  );

  // Light beyond the door.
  c.drawRect(
    opening,
    Paint()
      ..shader = Gradient.radial(
        gapCenter,
        opening.height * .6,
        const [Color(0xFFFFF4DC), Color(0xFFE8B070), Color(0xFF6A3A1C)],
        const [0, .45, 1],
      ),
  );

  // Someone standing in the light: thin, too tall, shoulders slightly hunched.
  final fig = Paint()
    ..color = const Color(0xFF120B08)
    ..maskFilter = MaskFilter.blur(BlurStyle.normal, s / 500);
  final fx = gapCenter.dx + opening.width * .02;
  final headR = s * .026;
  final headY = opening.top + opening.height * .3;
  c.drawOval(
    Rect.fromCenter(
      center: Offset(fx, headY),
      width: headR * 1.7,
      height: headR * 2.3,
    ),
    fig,
  );
  c.drawPath(
    Path()
      ..moveTo(fx - headR * .4, headY + headR * 1.05)
      ..quadraticBezierTo(
        fx - headR * 1.7,
        headY + headR * 1.4,
        fx - headR * 1.55,
        headY + headR * 3,
      )
      ..lineTo(fx - headR * 1.25, opening.bottom)
      ..lineTo(fx + headR * 1.25, opening.bottom)
      ..lineTo(fx + headR * 1.55, headY + headR * 3)
      ..quadraticBezierTo(
        fx + headR * 1.7,
        headY + headR * 1.4,
        fx + headR * .4,
        headY + headR * 1.05,
      )
      ..close(),
    fig,
  );

  // The door panel, swung inwards on its left hinge.
  final openW = opening.width * .58;
  final panel = Path()
    ..moveTo(opening.left, opening.top)
    ..lineTo(opening.left + openW, opening.top + opening.height * .04)
    ..lineTo(opening.left + openW, opening.bottom - opening.height * .03)
    ..lineTo(opening.left, opening.bottom)
    ..close();
  c.drawPath(
    panel,
    Paint()
      ..shader = Gradient.linear(
        opening.topLeft,
        Offset(opening.left + openW, opening.top),
        const [Color(0xFF3B2A1E), Color(0xFF2A1C13), Color(0xFF120B07)],
        const [0, .6, 1],
      ),
  );
  // Recessed panels in perspective.
  final inset = Paint()
    ..color = const Color(0x66000000)
    ..style = PaintingStyle.stroke
    ..strokeWidth = math.max(1, s / 200);
  for (final (top, bottom) in const [(.08, .44), (.52, .9)]) {
    c.drawPath(
      Path()
        ..moveTo(
          opening.left + openW * .18,
          opening.top + opening.height * (top + .005),
        )
        ..lineTo(
          opening.left + openW * .8,
          opening.top + opening.height * (top + .025),
        )
        ..lineTo(
          opening.left + openW * .8,
          opening.top + opening.height * (bottom - .02),
        )
        ..lineTo(
          opening.left + openW * .18,
          opening.top + opening.height * bottom,
        )
        ..close(),
      inset,
    );
  }
  // Brass knob on the far edge.
  c.drawCircle(
    Offset(opening.left + openW * .86, opening.top + opening.height * .54),
    s * .014,
    Paint()..color = const Color(0xFF9A8058),
  );

  // Light pouring across the floor.
  final gapLeft = opening.left + openW;
  c.drawPath(
    Path()
      ..moveTo(gapLeft, opening.bottom)
      ..lineTo(opening.right, opening.bottom)
      ..lineTo(opening.right + s * .22, s * 1.05)
      ..lineTo(gapLeft - s * .06, s * 1.05)
      ..close(),
    Paint()
      ..shader = Gradient.linear(
        Offset(0, opening.bottom),
        Offset(0, s),
        const [Color(0x99F0C890), Color(0x00F0C890)],
      ),
  );
  // Its shadow, stretched across the light on the floor.
  c.drawPath(
    Path()
      ..moveTo(fx - headR * 1.2, opening.bottom)
      ..lineTo(fx + headR * 1.2, opening.bottom)
      ..lineTo(fx + s * .1, s * 1.05)
      ..lineTo(fx - s * .02, s * 1.05)
      ..close(),
    Paint()
      ..shader = Gradient.linear(
        Offset(0, opening.bottom),
        Offset(0, s),
        const [Color(0xCC0A0605), Color(0x000A0605)],
      ),
  );
  c.restore();
}

// =================================================================== PNG

Future<void> _write(
  String path,
  int px,
  void Function(Canvas canvas, double size) paint, {
  required bool opaque,
}) async {
  final recorder = PictureRecorder();
  paint(Canvas(recorder), px.toDouble());
  final image = await recorder.endRecording().toImage(px, px);
  final data = await image.toByteData(format: ImageByteFormat.rawStraightRgba);
  image.dispose();
  File(path)
    ..createSync(recursive: true)
    ..writeAsBytesSync(_png(data!, px, px, opaque: opaque));
}

/// Minimal PNG encoder: 8-bit RGB (opaque) or RGBA, no filtering.
Uint8List _png(ByteData rgba, int w, int h, {required bool opaque}) {
  final channels = opaque ? 3 : 4;
  final raw = Uint8List(h * (1 + w * channels));
  var o = 0;
  for (var y = 0; y < h; y++) {
    raw[o++] = 0;
    for (var x = 0; x < w; x++) {
      final i = (y * w + x) * 4;
      for (var ch = 0; ch < channels; ch++) {
        raw[o++] = rgba.getUint8(i + ch);
      }
    }
  }

  final out = BytesBuilder()..add(const [137, 80, 78, 71, 13, 10, 26, 10]);
  void chunk(String type, List<int> body) {
    final typeBytes = ascii.encode(type);
    out
      ..add(_u32(body.length))
      ..add(typeBytes)
      ..add(body)
      ..add(_u32(_crc32([...typeBytes, ...body])));
  }

  chunk('IHDR', [..._u32(w), ..._u32(h), 8, opaque ? 2 : 6, 0, 0, 0]);
  chunk('IDAT', ZLibEncoder(level: 9).convert(raw));
  chunk('IEND', const []);
  return out.takeBytes();
}

List<int> _u32(int v) => [
  (v >> 24) & 255,
  (v >> 16) & 255,
  (v >> 8) & 255,
  v & 255,
];

final _crcTable = List<int>.generate(256, (n) {
  var c = n;
  for (var k = 0; k < 8; k++) {
    c = (c & 1) != 0 ? 0xEDB88320 ^ (c >> 1) : c >> 1;
  }
  return c;
});

int _crc32(List<int> bytes) {
  var c = 0xFFFFFFFF;
  for (final b in bytes) {
    c = _crcTable[(c ^ b) & 0xFF] ^ (c >> 8);
  }
  return c ^ 0xFFFFFFFF;
}
